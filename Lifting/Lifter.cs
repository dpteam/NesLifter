        /// <summary>
        /// Size of the cartridge WRAM window, in bytes.
        /// iNES 2.0 headers carry the real size; iNES 1.0 headers do not, so
        /// the mapper's conventional size is used.
        /// </summary>
        private int ResolveWramSize(CartInfo cart)
        {
            int declared = cart.PrgRamSize + cart.PrgRamSaveSize;

            if (declared > 0)
                return RoundUpPow2(declared, 0x2000);

            int conventional = _mapperDescriptor.DefaultPrgRam;

            return conventional > 0 ? conventional : 0x2000;
        }

        /// <summary>
        /// Size of the CHR RAM buffer for CHR-RAM cartridges.
        /// </summary>
        private static int ResolveChrRamSize(CartInfo cart)
        {
            int declared = cart.ChrRamSize + cart.ChrRamSaveSize;

            if (declared > 0)
                return RoundUpPow2(declared, 0x2000);

            return 0x2000;
        }

        private static int RoundUpPow2(int value, int minimum)
        {
            int size = minimum;

            while (size < value)
                size <<= 1;

            return size;
        }

        /// <summary>
        /// Emits a ROM byte array. This is data, not code: one line per 16 bytes
        /// keeps the generated file's line count sane for multi-hundred-KB ROMs.
        /// </summary>
        private static void AppendByteArrayField(StringBuilder sb, string name, byte[] data)
        {
            if (data == null || data.Length == 0)
            {
                sb.AppendLine($"    public static readonly byte[] {name} = new byte[0];");
                return;
            }

            sb.AppendLine($"    public static readonly byte[] {name} = new byte[] {{");

            const int Chunk = 16;

            for (int i = 0; i < data.Length; i += Chunk)
            {
                sb.Append("        ");

                int end = Math.Min(i + Chunk, data.Length);

                for (int j = i; j < end; j++)
                {
                    sb.Append("0x").Append(data[j].ToString("X2"));

                    if (j < data.Length - 1)
                        sb.Append(", ");
                }

                sb.AppendLine();
            }

            sb.AppendLine("    };");
        }

        /// <summary>
        /// Escapes a free-form string for embedding in a C# string literal. Titles
        /// are ROM filenames, so they can contain quotes, backslashes and non-ASCII
        /// characters that would otherwise produce broken generated code.
        /// </summary>
        private static string EscapeStringLiteral(string text)
        {
            if (string.IsNullOrEmpty(text))
                return string.Empty;

            StringBuilder sb = new StringBuilder(text.Length + 8);

            foreach (char c in text)
            {
                switch (c)
                {
                    case '\\': sb.Append("\\\\"); break;
                    case '"': sb.Append("\\\""); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < 0x20 || c > 0x7E)
                            sb.Append("\\u").Append(((int)c).ToString("X4"));
                        else
                            sb.Append(c);
                        break;
                }
            }

            return sb.ToString();
        }

        private static string SanitizeIdentifier(string name)
        {
            if (string.IsNullOrEmpty(name))
                return "Game";

            StringBuilder sb = new StringBuilder();

            foreach (char c in name)
            {
                if (char.IsLetterOrDigit(c) || c == '_')
                    sb.Append(c);
                else
                    sb.Append('_');
            }

            if (sb.Length == 0)
                sb.Append("Game");

            if (char.IsDigit(sb[0]))
                sb.Insert(0, '_');

            return "Game_" + sb.ToString();
        }

        private static void Line(StringBuilder sb, string text)
        {
            sb.AppendLine("            " + text);
        }

        /// <summary>
        /// Appends a raw string literal verbatim, normalising line endings.
        ///
        /// Raw literals keep braces, quotes and backslashes exactly as written,
        /// so the emitted C# in this file is readable as C# instead of a wall of
        /// escaped <c>\"</c> sequences. Dedentation is handled by the compiler,
        /// which is why the literal bodies are indented with the surrounding code.
        /// </summary>
        private static string Raw(string text)
        {
            return text.Replace("\r\n", "\n").Replace("\n", Environment.NewLine) + Environment.NewLine;
        }

                    public static void Reset()
                    {
                        Ctrl = Mask = OamAddr = ScrollX = ScrollY = 0;
                        // At power-on the PPU is not in VBlank. SMB waits for this
                        // edge before initializing the title screen and VRAM.
                        Status = 0;
                        WToggle = false;

                        public static bool CheckNmi(ushort pc)
                        {
                            if (CpuCycles >= NextThrottleCycle) { NextThrottleCycle = CpuCycles + 2048; Throttle(); }
                            if (VblankClearCycle != 0 && CpuCycles >= VblankClearCycle) { Ppu.Status = (byte)(Ppu.Status & 0x1F); VblankClearCycle = 0; }

                            if (CpuCycles >= NextVblankCycle)
                            {
                                NextVblankCycle += 29780;
                                VblankClearCycle = CpuCycles + 2273;
                                Ppu.FrameCount++;
                                ThrottleFrame();
                                NmiPending = true;
                                Ppu.Status = (byte)(Ppu.Status | 0x80);
                                Ppu.BeginFrame();
                                Runtime.SampleFps();
                                if (Diag.Any) Diag.FlushAll();
                                Log("nmi", "vblank/frame=" + Ppu.FrameCount + " cycles=" + CpuCycles + " pc=$" + pc.ToString("X4"), false);

                                // Park here so a headless driver can capture this exact frame.
                                if (Headless) Runtime.HeadlessPublishFrame();
                            }

                            if (!NmiPending || (Ppu.Ctrl & 0x80) == 0)
                            {
                                if ((Ppu.Ctrl & 0x80) == 0) NmiPending = false;
                                return false;
                            }

                            // Hardware nests: if the NMI line is asserted again while
                            // the handler is still running, the CPU takes it again.
                            // That is correct behaviour and a healthy handler never
                            // gets here twice, but an interrupt handler that runs
                            // slower than a frame would recurse until the stack
                            // wrapped вЂ” so nesting is capped and reported.
                            if (IntDepth >= MaxIntDepth)
                            {
                                NmiPending = false;
                                Log("nmi-nest", "NMI handler still running after " + MaxIntDepth
                                    + " levels at frame " + Ppu.FrameCount + "; dropping this one", true);
                                return false;
                            }

                            NmiPending = false;
                            IntDepth++;

                            if (Diag.TraceDispatch) Diag.NmiTaken(pc, CpuCycles, NextVblankCycle, IntDepth);

                            Push16(pc);
                            Push((byte)((P & 0xEF) | 0x20));
                            P = (byte)(P | 0x04);

                            return true;
                        }

                        public static bool CheckIrq(ushort pc)
                        {
                            if (!IrqPending) return false;
                            if ((P & 0x04) != 0) return false;

                            if (IntDepth >= MaxIntDepth)
                            {
                                IrqPending = false;
                                return false;
                            }

                            IrqPending = false;
                            IntDepth++;

                            Push16(pc);
                            Push((byte)((P & 0xEF) | 0x20));
                            P = (byte)(P | 0x04);
                            return true;
                        }


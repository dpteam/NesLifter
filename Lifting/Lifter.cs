        private void AppendRun(StringBuilder sb)
        {
            bool hasEntry = _model.EntryOffset >= 0 && _labels.Contains(_model.EntryOffset);

            sb.Append(Raw($$"""
                        public static void Run()
                        {
                            try
                            {
                                Runtime.CpuState = "Running";
                                Console.WriteLine("CPU started. Entry: 0x{{_model.Entry.ToString("X4")}}");
                                Console.WriteLine("Press Ctrl+C to exit.");
                """));

            if (hasEntry)
                Line(sb, "goto " + Label(_model.EntryOffset) + ";");
            else
                Line(sb, "Runtime.Trap(\"No valid entry/reset vector.\"); return;");

            // Dispatch: the CPU hands us an address, the mapper resolves it to a
            // PRG offset, and the offset selects the block. Keying on offset is
            // what lets one lift cover every bank of the cartridge.
            if (_emitted.Count > 0)
            {
                sb.Append(Raw("""
                            Dispatch:
                                {
                                    // --force-interpreter routes everything through the
                                    // interpreter. Running a title both ways and diffing
                                    // the state dumps is a self-check that needs no
                                    // external emulator: if the two runs diverge, the
                                    // lifted code is wrong; if they agree and both fail,
                                    // the bug is in the runtime (PPU, APU, mapper).
                                    if (Runtime.ForceInterpreter)
                                    {
                                        if (Diag.TraceDispatch) Diag.Dispatch(Runtime.DispatchTarget, "forced interpreter");
                                        if (!Runtime.Interpret()) { Runtime.Trap("Forced interpreter stopped at $" + Runtime.DispatchTarget.ToString("X4")); return; }
                                        goto Dispatch;
                                    }

                                    int off = MapperStub.ToOffset(Runtime.DispatchTarget);
                                    switch (off)
                                    {
                    """));

                foreach (int offset in _emitted)
                    Line(sb, "case 0x" + offset.ToString("X6") + ": goto " + Label(offset) + ";");

                sb.Append(Raw("""
                                        default: if (Diag.TraceDispatch) Diag.Dispatch(Runtime.DispatchTarget, "not lifted"); Runtime.ReportDynamicTarget(Runtime.DispatchTarget); if (!Runtime.Interpret()) { Runtime.Trap("Dynamic dispatch -> $" + Runtime.DispatchTarget.ToString("X4")); return; } goto Dispatch;
                                    }
                                }
                    """));
            }

            // Emitted instructions
            foreach (int offset in _emitted)
            {
                sb.AppendLine("    " + Label(offset) + ":");
                sb.AppendLine("        {");

                Instruction? inst;
                _model.Instructions.TryGetValue(offset, out inst);

                ushort display = inst?.Address ?? 0;
                string hex = display.ToString("X4");

                Line(sb, "Runtime.LastPC = 0x" + hex + "; Runtime.TraceInstruction(0x" + hex + ");");

                // CPU trace hook: one line per instruction, only when enabled.
                if (inst != null)
                    Line(sb, "if (Diag.TraceCpu) Diag.CpuStep(0x" + hex + ", 0x" + inst.Opcode.ToString("X2") + ");");
                else
                    Line(sb, "if (Diag.TraceCpu) Diag.CpuStep(0x" + hex + ", 0x00);");

                if (inst != null && inst.Info != null)
                    Line(sb, "Runtime.InsCount++; Runtime.AdvanceCycles(" + inst.Info.Cycles + ");");
                else
                    Line(sb, "Runtime.InsCount++; Runtime.AdvanceCycles(1);");

                // The NMI/IRQ vectors live at the top of the address space, which
                // is fixed on most boards but remapped wholesale on AxROM-style
                // mappers. Resolving through the dispatcher costs one indirect
                // branch per frame and is correct on both.
                if (_nmiOffset >= 0)
                    Line(sb, "if (Runtime.CheckNmi(0x" + hex + ")) { Runtime.DispatchTarget = Runtime.NmiVector; goto Dispatch; }");

                Line(sb, "if (Runtime.CheckIrq(0x" + hex + ")) { Runtime.DispatchTarget = Runtime.IrqVector; goto Dispatch; }");

                if (inst != null)
                {
                    Line(sb, "// " + inst.Text);
                    EmitInstruction(sb, inst);
                }
                else
                {
                    Line(sb, "Runtime.Trap(\"Label without instruction.\"); return;");
                }

                sb.AppendLine("        }");
            }

            sb.Append(Raw("""
                            }
                            catch (Exception ex) { OnCpuException(ex); }
                        }

                """));
        }


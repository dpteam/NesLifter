        private string GetBranchCondition(string mn)
        {
            switch (mn)
            {
                case "BPL": return "(Runtime.P & 0x80) == 0";
                case "BMI": return "(Runtime.P & 0x80) != 0";
                case "BVC": return "(Runtime.P & 0x40) == 0";
                case "BVS": return "(Runtime.P & 0x40) != 0";
                case "BCC": return "(Runtime.P & 0x01) == 0";
                case "BCS": return "(Runtime.P & 0x01) != 0";
                case "BNE": return "(Runtime.P & 0x02) == 0";
                case "BEQ": return "(Runtime.P & 0x02) != 0";
                default: return "true";
            }
        }

        private string GetReadExpr(Instruction inst)
        {
            switch (inst.Info.Mode)
            {
                case AddrMode.Imm: return "0x" + inst.Operand.ToString("X2");
                case AddrMode.Acc: return "Runtime.A";
                case AddrMode.Imp: return "0";
                default: return "Memory.Read(" + GetAddressExpr(inst) + ")";
            }
        }

        private string GetAddressExpr(Instruction inst)
        {
            string op2 = inst.Operand.ToString("X2");
            string op4 = inst.Operand.ToString("X4");

            switch (inst.Info.Mode)
            {
                case AddrMode.Zp: return "0x" + op2;
                case AddrMode.ZpX: return "(ushort)((0x" + op2 + " + Runtime.X) & 0xFF)";
                case AddrMode.ZpY: return "(ushort)((0x" + op2 + " + Runtime.Y) & 0xFF)";
                case AddrMode.Abs: return "0x" + op4;
                case AddrMode.AbsX: return "unchecked((ushort)(0x" + op4 + " + Runtime.X))";
                case AddrMode.AbsY: return "unchecked((ushort)(0x" + op4 + " + Runtime.Y))";
                case AddrMode.XInd: return "Runtime.AddrXInd(0x" + op2 + ")";
                case AddrMode.IndY: return "Runtime.AddrIndY(0x" + op2 + ")";
                default: return "0";
            }
        }

